hl.window_rule({
	match = {
		class = "^$",
		title = "^$",
		xwayland = 1,
		float = 0,
		fullscreen = 0,
		pin = 0,
	},
	no_focus = true,
})

-- Prevent apps from auto-maximizing themselves
hl.window_rule({
	match = {
		class = ".*",
	},
	suppress_event = "maximize",
})

